test('late search responses do not overwrite the latest query', async ({ page }) => {
  await page.goto(await testDiagram(page))
  await ready(page)
  await picker(page, 'Задачи')
  const item = await (await page.request.post('/api/tracker/RACE-1')).json()
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  let started = false
  await page.route('**/api/tracker?**', async route => {
    const query = new URL(route.request().url()).searchParams.get('q')
    if (query === 'первый') {
      started = true
      await gate
      await route.fulfill({ json: { items: [item], nextOffset: null } }).catch(() => {})
    } else await route.fulfill({ json: { items: [], nextOffset: null } })
  })
  try {
    await page.getByLabel('Поиск задач', { exact: true }).fill('первый')
    await expect.poll(() => started).toBe(true)
    await page.getByLabel('Поиск задач', { exact: true }).fill('последний')
    await expect(page.getByText('Задачи не найдены.')).toBeVisible()
    release()
    await expect(page.getByRole('navigation', { name: 'Список задач' }).getByRole('link')).toHaveCount(0)
    await expect(page.getByLabel('Поиск задач', { exact: true })).toHaveValue('последний')
  } finally { release() }
})

