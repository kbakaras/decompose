const root = (page: Page) => page.locator('[data-cell-id="root"]')
const ready = async (page: Page) => {
  await expect(page.locator('main')).toHaveAttribute('data-ready', 'true')
}
async function rename(page: Page, text: string) {
  await root(page).dblclick()
  await page.getByRole('textbox', { name: 'Текст клеточки' }).fill(text)
  await page.keyboard.press('Enter')
  await expect(root(page)).toHaveAttribute('data-text', text)
}
async function picker(page: Page, section: 'Схемы' | 'Задачи') {
  await page.getByRole('button', { name: 'Схемы', exact: true }).click()
  await page.getByRole('tablist', { name: 'Раздел каталога' }).getByRole('tab', { name: section, exact: true }).click()
}
async function navigate(page: Page, path: string) {
  await page.evaluate(path => {
    history.pushState(null, '', path)
    dispatchEvent(new PopStateEvent('popstate'))
  }, path)
}

